const renderNavigation = () => {
    if (nav) {
        const navHTML = navLinks.map(link => {
            return `
            <a href="${link.href}" class="nav-link">${link.label}</a>
            `;}).join("");
            nav.innerHTML = navHTML;
        };
        if (mobileMenu) {
            const mobileMenu = navLinks.map(link => {
                return `
                <a href="${link.href}" class="mobile-link">${link.label}</a>
                `;}).join("");
                mobileMenu.innerHTML = mobileMenu;
            };
        };
// array.map()
// -> returns the array as HTML
// -> join("") method used to shape them into one HTML string
// -> insert them into the DOM using the innerHTML
// Our Navigation now:
// comes from data (data driven)
// updates instantly if the array changes
// works in the desktop view and mobile view
// uses modern JS patterns

// This: nav Links.map(link =>....)
// Is basically: {navLinks.map(link...)} in React

